// Compute WCAG contrast ratios for every theme's :root (light) and .dark
// token pairs, and record the numbers in docs/accessibility/contrast.md so
// they can be re-verified by reading the file instead of re-deriving them by
// hand. The same math backs src/__tests__/theme-contrast.test.ts, which is
// what actually gates CI — this script's job is only to (re)generate the
// recorded table; run it after changing any theme's color tokens.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { scoreThemeMode, tokensInBlock } from "./lib/color-contrast.mjs";

const THEMES_DIR = "src/styles/themes";
const OUT_FILE = "docs/accessibility/contrast.md";

const themeFiles = readdirSync(THEMES_DIR)
	.filter((f) => f.endsWith(".css"))
	.sort();

const rows = [];
let failCount = 0;

for (const file of themeFiles) {
	const theme = file.replace(/\.css$/, "");
	const css = readFileSync(join(THEMES_DIR, file), "utf-8");

	for (const [mode, selector] of [
		["light", ":root"],
		["dark", "\\.dark"],
	]) {
		const tokens = tokensInBlock(css, selector);
		const results = scoreThemeMode(tokens);
		for (const r of results) {
			if (!r.pass) failCount++;
			rows.push({ theme, mode, ...r });
		}
	}
}

const header = `# Token contrast report

<!-- Generated by \`node scripts/check-contrast.mjs\` — do not hand-edit. -->

WCAG contrast ratio for every foreground/background token pair defined in
\`src/styles/themes/*.css\`, for every theme, in both \`:root\` (light) and
\`.dark\`. \`min\` is the WCAG 2.1 AA threshold that pair is held to — 4.5:1 for
body text, 3.0:1 for the bold/large UI-accent text these components render
(button labels, badge text). The same thresholds are asserted in CI by
\`src/__tests__/theme-contrast.test.ts\`; this file is the recorded, re-checkable
numbers behind that assertion, not a separate source of truth.

Regenerate after changing any theme's color tokens: \`node scripts/check-contrast.mjs\`.

| Theme | Mode | Pair | Ratio | Min | Result |
|---|---|---|---:|---:|---|
`;

const body = rows
	.map(
		(r) =>
			`| ${r.theme} | ${r.mode} | \`${r.fg}\` on \`${r.bg}\` | ${r.ratio.toFixed(2)}:1 | ${r.minRatio.toFixed(1)}:1 | ${r.pass ? "✅ pass" : "❌ fail"} |`,
	)
	.join("\n");

const footer = `\n\n${failCount === 0 ? `All ${rows.length} pairs meet their threshold.` : `${failCount} of ${rows.length} pairs fall short of their threshold.`}\n`;

writeFileSync(OUT_FILE, header + body + footer);
console.log(`wrote ${rows.length} rows (${failCount} failing) to ${OUT_FILE}`);
if (failCount > 0) process.exitCode = 1;
